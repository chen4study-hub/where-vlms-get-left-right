"""Analyses A-K below, computed from the per-item predictions of several runs. All analyses in this module are post hoc.

  python -m experiments.posthoc_analyses summary
      A. left-right change rate under vit_w on the geometry-consistent subset, split by the original answer
      B. 'neither' class of the position / content / neither decomposition, split by whether the real flip changes it
      C. paired bootstrap of vit_h minus vit_w change rate, CV-Bench 3D depth test half
      D. Qwen2.5-VL M-RoPE: frequencies of the width channels and the angle change under the LLM-side width mirror
      E. depth specificity: difference in differences of the vit_h and vit_w change rates between the items whose
         original answer follows the 'higher means farther' heuristic and the others (validation and test half)
      F. InternVL3-2B: rotation-angle change of the 1D RoPE under the LLM-side width mirror
      G. InternVL3-2B bf16 ties on CV-Bench; per-item differences between Qwen2.5-VL-7B and InternVL3-8B
      H. direction (right->left, left->right) of the left-right changes under the block-wise width mirrors
      I. permutation controls: depth permutations split by whether the original answer follows the heuristic;
         share of 'left' answers of Qwen2.5-VL-3B with the ViT width code removed

  python -m experiments.posthoc_analyses content-and-errors
      J. What'sUp content-only control, direction measure: on the geometry-consistent items (orig and real flip
         both correct), share of answers under pix_both that return to the orig answer, up-down minus left-right
      K. CV-Bench: share of the wrong orig answers that equal the same model's blank-image answer
Bootstrap: 10000 resamples, seed 0 (unpaired: each resample draws the first group, then the second).
"""
import argparse
import collections
import math
import random

from vlmlr import cvbench as C
from vlmlr.records import read_jsonl
from vlmlr.stats import bootstrap, wilson

MAIN = {"3b": "results/main_table/qwen2.5-vl/qwen2.5-vl-3b-instruct.jsonl",
        "7b": "results/main_table/qwen2.5-vl/qwen2.5-vl-7b-instruct.jsonl",
        "ivl": "results/main_table/internvl3-2b/internvl3-2b-hf.jsonl"}
BLANK = {"3b": "results/decomposition/blank_image/blank_qwen2.5-vl-3b-instruct.jsonl",
         "7b": "results/decomposition/blank_image/blank_qwen2.5-vl-7b-instruct.jsonl",
         "ivl": "results/decomposition/blank_image_fp32/blank_internvl3-2b-hf.jsonl"}
DEPTH_TEST = {"3b": "results/depth_shortcut/cvbench3d_test/test_qwen2.5-vl-3b-instruct.jsonl",
              "7b": "results/depth_shortcut/cvbench3d_test/test_qwen2.5-vl-7b-instruct.jsonl"}
DEPTH_VAL = {"3b": "results/depth_shortcut/cvbench3d_val/qwen2.5-vl-3b-instruct.jsonl",
             "7b": "results/depth_shortcut/cvbench3d_val/qwen2.5-vl-7b-instruct.jsonl"}
IVL8B = "results/main_table/internvl3-8b/internvl3-8b-hf.jsonl"
BLOCKS = "results/blocks_dose/blocks_qwen2.5-vl-{m}-instruct.jsonl"
CTRL = "results/permutation_controls/q{m}_{data}.jsonl"
CONTENT = "results/further_checks/vertical_content/{m}_whatsup.jsonl"
INV = {"left": "right", "right": "left", "above": "below", "below": "above", "on": "under", "under": "on"}


def _by_item(recs):
    out = collections.defaultdict(dict)
    for r in recs:
        out[r["idx"]][r["variant"]] = r
    return out


def _pct(k, n):
    return f"{100 * k / n:.1f}% ({k}/{n})" if n else "n/a"


def _paired(a, b):
    """Mean of b - a in points with a paired bootstrap interval (resampled item indices)."""
    bs = bootstrap(lambda s: sum(b[k] - a[k] for k in s) / len(a), len(a))
    return f"{100 * (sum(b) - sum(a)) / len(a):+.1f} [{100 * bs[249]:+.1f}, {100 * bs[9749]:+.1f}]"


def summary():
    from experiments.decomposition import answer_source, index_sources
    print("# Generated by python -m experiments.posthoc_analyses summary (analyses A-I of the per-item predictions).")
    print("== A. vit_w flip split by original answer (CV-Bench left-right, geometry-consistent subset)")
    for m, p in MAIN.items():
        R = _by_item(read_jsonl(p))
        lr = [i for i in R if R[i]["orig"]["axis"] == "lr"]
        gc = [i for i in lr if R[i]["orig"]["pred"] == R[i]["orig"]["expected"]
              and R[i]["hflip"]["pred"] == R[i]["hflip"]["expected"]]
        for lab in ("left", "right"):
            S = [i for i in gc if R[i]["orig"]["pred"] == lab]
            print(f"{m} orig={lab}: flip {_pct(sum(R[i]['vit_w']['pred'] != R[i]['orig']['pred'] for i in S), len(S))}")
        print(f"{m} vit_w answers left (all lr): {_pct(sum(R[i]['vit_w']['pred'] == 'left' for i in lr), len(lr))}")
        print(f"{m} orig answers left (all lr): {_pct(sum(R[i]['orig']['pred'] == 'left' for i in lr), len(lr))}")

    print("== B. 'neither' class (follows neither the position mirror nor the content) split by the real flip (all items)")
    for m in MAIN:
        items = index_sources(read_jsonl(MAIN[m]), read_jsonl(BLANK[m]))
        for ax in ("lr", "ud"):
            Q = [q for q in items.values() if q["axis"] == ax and answer_source(q) == "neither"]
            print(f"{m} {ax} neither-class items changing under the real flip: {_pct(sum(q['real'] != q['orig'] for q in Q), len(Q))}")

    print("== C. Paired bootstrap, vit_h minus vit_w change rate (CV-Bench 3D depth, test half; 10000 resamples, seed 0)")
    for m, p in DEPTH_TEST.items():
        R = collections.defaultdict(dict)
        for r in read_jsonl(p):
            if r["task"] == "Depth":
                R[r["idx"]][r["cond"]] = 0 if r["lp"][0] > r["lp"][1] else 1   # fp32, no ties in this run
        ids = sorted(i for i in R if all(v in R[i] for v in ("orig", "vit_h", "vit_w")))
        d = [(R[i]["vit_h"] != R[i]["orig"]) - (R[i]["vit_w"] != R[i]["orig"]) for i in ids]
        bs = bootstrap(lambda s: sum(d[k] for k in s) / len(d), len(d))
        print(f"{m} vit_h - vit_w: {100 * sum(d) / len(d):+.1f} [{100 * bs[249]:+.1f}, {100 * bs[9749]:+.1f}] n={len(d)}")

    print("== D. Qwen2.5-VL M-RoPE width channels and LLM-side width-mirror angle change")
    # config of Qwen2.5-VL-3B/7B-Instruct: rope_theta 1e6, head_dim 128, mrope_section [16, 24, 24] (t, h, w), so the
    # width component takes the last 24 of the 64 frequencies
    theta, dim, sec = 1e6, 128, [16, 24, 24]
    inv = [theta ** (-2 * i / dim) for i in range(dim // 2)]
    f = inv[sec[0] + sec[1]:]
    print(f"w: frequency range {max(f):.2e} .. {min(f):.2e} rad per position")
    width = 36                          # max_pixels 1280*28*28 allows at most 1280 merged tokens; 36 x 36 is the square case
    print(f"w mirror, image {width} merged tokens wide: largest angle change {max(f) * (width - 1):.4f} rad (highest w frequency)")
    print("== E. Depth specificity, difference in differences (paired bootstrap over items, 10000 resamples, seed 0)")
    # (vit_h change rate, heuristic-following group - other group) - (vit_w change rate, same groups); an item enters only
    # if orig, vit_h and vit_w are all untied, so the group sizes can differ slightly from the per-condition rates.
    for half, files in (("validation", DEPTH_VAL), ("test", DEPTH_TEST)):
        for m, p in files.items():
            R = collections.defaultdict(dict)
            for r in read_jsonl(p):
                if r["task"] == "Depth":
                    R[r["idx"]][r["cond"]] = r
            rows = []
            for v in R.values():
                if v["orig"]["group"] not in ("consistent", "counter") or not all(c in v for c in ("vit_h", "vit_w")):
                    continue
                if any(v[c]["lp"][0] == v[c]["lp"][1] for c in ("orig", "vit_h", "vit_w")):
                    continue
                pr = {c: int(v[c]["lp"][1] > v[c]["lp"][0]) for c in ("orig", "vit_h", "vit_w")}
                g = v["orig"]["gold"]
                heur = g if v["orig"]["group"] == "consistent" else 1 - g
                rows.append((pr["orig"] == heur, pr["vit_h"] != pr["orig"], pr["vit_w"] != pr["orig"]))

            def did(rs):
                con = [r for r in rs if r[0]]
                inc = [r for r in rs if not r[0]]
                if not con or not inc:
                    return float("nan")
                rate = lambda grp, j: sum(r[j] for r in grp) / len(grp)
                return (rate(con, 1) - rate(inc, 1)) - (rate(con, 2) - rate(inc, 2))
            bs = sorted(bootstrap(lambda s: did([rows[k] for k in s]), len(rows)))
            ncon = sum(r[0] for r in rows)
            print(f"{m} {half}: DiD {100 * did(rows):+.1f} [{100 * bs[249]:+.1f}, {100 * bs[9749]:+.1f}] n={len(rows)} "
                  f"(follows {ncon}, against {len(rows) - ncon})")

    print("== F. InternVL3-2B LLM-side width mirror: rotation-angle change")
    # OpenGVLab/InternVL3-2B-hf config: rope_theta 1e6, head_dim 128; 1D RoPE with consecutive position ids. One 448x448
    # tile = 16 x 16 visual tokens in row-major order; the LLM-side width mirror reverses the ids within each row of 16.
    theta, dim, row = 1e6, 128, 16
    inv = [theta ** (-2 * i / dim) for i in range(dim // 2)]
    shifts = [abs((row - 1 - c) - c) for c in range(row)]
    print(f"id change within a row: max {max(shifts)}, mean {sum(shifts) / row:.1f} positions")
    wrapped = [min((f * s) % (2 * math.pi), 2 * math.pi - (f * s) % (2 * math.pi)) for f in inv for s in shifts]
    print(f"mean angle change over channels and tokens, wrapped to [0, pi]: {sum(wrapped) / len(wrapped):.2f} rad")

    print("== G. InternVL3-2B bf16 ties on CV-Bench, and per-item differences between Qwen2.5-VL-7B and InternVL3-8B")
    rows = C.main_rows(read_jsonl(MAIN["ivl"]))
    print(f"ivl CV-Bench rows {len(rows)}, bf16 ties {_pct(sum(r['logp'][0] == r['logp'][1] for r in rows), len(rows))}")
    R7, R8 = _by_item(read_jsonl(MAIN["7b"])), _by_item(read_jsonl(IVL8B))
    for v in ("orig", "vit_w", "vit_h", "hflip"):
        ids = [i for i in R7 if v in R7[i] and i in R8 and v in R8[i]]
        print(f"7b vs 8b, {v}: answers differ on {sum(R7[i][v]['pred'] != R8[i][v]['pred'] for i in ids)} of {len(ids)} items")

    print("== H. Direction of the left-right changes under block-wise width mirrors (Qwen2.5-VL, all 383 left-right items)")
    for m in ("3b", "7b"):
        B = collections.defaultdict(dict)
        for r in read_jsonl(BLOCKS.format(m=m)):
            B[r["idx"]][r["cond"]] = r
        for c in ("orig_vit_all", "orig_vit_blk31", "orig_vit_all_but_last"):
            ids = [i for i in B if B[i]["base_orig"]["axis"] == "lr" and c in B[i]]
            rl = sum(B[i]["base_orig"]["pred"] == "right" and B[i][c]["pred"] == "left" for i in ids)
            lr = sum(B[i]["base_orig"]["pred"] == "left" and B[i][c]["pred"] == "right" for i in ids)
            print(f"{m} {c}: right->left {rl}, left->right {lr} (n={len(ids)})")

    print("== I. Permutation controls, post hoc: depth permutations split by whether the original answer follows the "
          "heuristic; 3B answers after neutralizing")
    # held-out depth half, fp32 scoring (rows with an exact fp32 tie are skipped); non-ambiguous items; rates pooled over
    # the four permutations of an axis. The original answer follows the heuristic when the object chosen as closer is
    # the lower one (pred != higher).
    for m in ("3b", "7b"):
        D = collections.defaultdict(dict)
        for r in read_jsonl(CTRL.format(m=m, data="depth")):
            D[r["idx"]][r["cond"]] = r
        for ax in ("vit_h", "vit_w"):
            conds = [f"{ax}_shift"] + [f"{ax}_shuf{s}" for s in range(3)]
            out = []
            for lab, follows in (("follows", True), ("against", False)):
                ids = [i for i in D if D[i]["orig"]["group"] != "ambiguous" and not D[i]["orig"]["tie32"]
                       and (D[i]["orig"]["pred"] != D[i]["orig"]["higher"]) == follows]
                rows = [(i, c) for i in ids for c in conds if not D[i][c]["tie32"]]
                k = sum(D[i][c]["pred"] != D[i]["orig"]["pred"] for i, c in rows)
                out.append(f"{lab} {_pct(k, len(rows))} [{len(ids)} items]")
            print(f"{m} {ax} permutations, change rate: " + " | ".join(out))
    rows = [r for r in read_jsonl(CTRL.format(m="3b", data="cv2d")) if r["cond"] == "neu" and r["axis"] == "lr"]
    print(f"3b neutralized width code, left-right answers 'left': {_pct(sum(r['pred'] == 'left' for r in rows), len(rows))}")


def _unpaired(f1, g1, f2, g2, B=10000, seed=0):
    """f1(g1) - f2(g2) with an unpaired bootstrap interval."""
    rng = random.Random(seed)
    g1, g2 = sorted(g1), sorted(g2)
    vals = sorted(f1([g1[rng.randrange(len(g1))] for _ in g1]) - f2([g2[rng.randrange(len(g2))] for _ in g2])
                  for _ in range(B))
    return f1(g1) - f2(g2), (vals[int(0.025 * B)], vals[int(0.975 * B) - 1])


def _rate(k, n):
    lo, hi = wilson(k, n)
    return f"{k}/{n} {100 * k / n:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def content_and_errors():
    print("# Generated by python -m experiments.posthoc_analyses content-and-errors (analyses J-K of the per-item predictions).")
    print("== J. What'sUp content-only control, direction measure (GC = orig and real flip both correct; "
          "unpaired bootstrap of up-down minus left-right)")
    axes = {"ud": ("vflip", "vflip_both_h"), "lr": ("hflip", "hflip_both_w")}
    for m, name in (("q3b", "3b"), ("q7b", "7b"), ("ivl2b", "ivl")):
        d = collections.defaultdict(dict)
        for r in read_jsonl(CONTENT.format(m=m)):
            d[r["idx"]][r["cond"]] = r
        gc = {ax: sorted(i for i, v in d.items() if v["orig"]["axis"] == ax and both in v
                         and v["orig"]["pred"] == v["orig"]["gold"] and v[pix]["pred"] == INV[v["orig"]["gold"]])
              for ax, (pix, both) in axes.items()}

        def back(ax):
            return lambda I: sum(d[i][axes[ax][1]]["pred"] == d[i]["orig"]["pred"] for i in I) / len(I)

        print(f"  {name}")
        for ax, lab in (("ud", "up-down"), ("lr", "left-right")):
            pix, both = axes[ax]
            G = gc[ax]
            kb = sum(d[i][both]["pred"] == d[i]["orig"]["pred"] for i in G)
            kc = sum(d[i][both]["pred"] == d[i][pix]["pred"] for i in G)
            print(f"    GC {lab} n={len(G)}: back to the orig answer {_rate(kb, len(G))}; "
                  f"equal to the real-flip answer {100 * kc / len(G):.1f}; other {100 * (len(G) - kb - kc) / len(G):.1f}")
        D, (lo, hi) = _unpaired(back("ud"), gc["ud"], back("lr"), gc["lr"])
        print(f"    back to the orig answer, up-down minus left-right {100 * D:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]")
    print("== K. CV-Bench: wrong orig answers that equal the same model's blank-image answer (Wilson 95%)")
    tot = [0, 0]
    for m in ("3b", "7b", "ivl"):
        o = {i: v["orig"] for i, v in _by_item(read_jsonl(MAIN[m])).items()}
        b = {i: v["blank"] for i, v in _by_item(read_jsonl(BLANK[m])).items()}
        assert set(o) == set(b), m
        mt = [0, 0]
        for ax, lab in (("lr", "left-right"), ("ud", "up-down")):
            ids = sorted(i for i in o if o[i]["axis"] == ax)
            W = [i for i in ids if o[i]["pred"] != o[i]["expected"]]
            R = [i for i in ids if o[i]["pred"] == o[i]["expected"]]
            k = sum(o[i]["pred"] == b[i]["pred"] for i in W)
            kr = sum(o[i]["pred"] == b[i]["pred"] for i in R)
            print(f"  {m:3s} {lab}: items {len(ids)}, wrong {len(W)}; wrong answers equal to the blank-image answer "
                  f"{_rate(k, len(W))}; correct answers equal to the blank-image answer {100 * kr / len(R):.1f} ({kr}/{len(R)})")
            mt[0] += k
            mt[1] += len(W)
        print(f"  {m:3s} both axes: {_rate(*mt)}")
        tot = [tot[0] + mt[0], tot[1] + mt[1]]
    print(f"  three models, both axes: {_rate(*tot)}")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m experiments.posthoc_analyses", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("summary", help="analyses A-I")
    sub.add_parser("content-and-errors", help="analyses J-K")
    a = ap.parse_args(argv)
    {"summary": summary, "content-and-errors": content_and_errors}[a.cmd]()


OUTPUTS = [
    ("outputs/posthoc_analyses/posthoc_analyses.txt", ["summary"], True),
    ("outputs/posthoc_analyses/content_and_errors.txt", ["content-and-errors"], True),
]

if __name__ == "__main__":
    main()
